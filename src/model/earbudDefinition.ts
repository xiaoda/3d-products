const pole = (x: number, y: number, z: number): ControlPointMm[] =>
  Array.from({ length: SHELL_COLUMNS }, () => [x, y, z]);

const tangentRing = (x: number, y: number, z: number, radius: number): ControlPointMm[] =>
  Array.from({ length: SHELL_COLUMNS }, (_, i) => {
    const angle = ((i - 1) * Math.PI * 2) / SHELL_COLUMNS;
    return [x + radius * Math.cos(angle), y, z + radius * Math.sin(angle)];
  });

